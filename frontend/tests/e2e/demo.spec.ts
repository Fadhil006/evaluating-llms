import { expect, test } from '@playwright/test'

test('offline demo runs, reports, and blinded review survives reload', async ({ page }) => {
  await page.goto('/')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('banner').getByRole('link', { name: 'Compare two models' })).toBeFocused()
  await page.goto('/models')
  await page.getByRole('button', { name: 'Refresh catalog' }).click()
  await expect(page.getByText(/no network calls/i)).toBeVisible()
  const availableModels = page.locator('details').filter({ has: page.getByText('Synthetic demonstration models (2)', { exact: true }) })
  await expect(availableModels).not.toHaveAttribute('open', '')
  await availableModels.locator(':scope > summary').click()
  await expect(availableModels.locator('summary').filter({ hasText: 'DEMONSTRATION — synthetic Alpha' })).toBeVisible()
  await expect(availableModels.locator('summary').filter({ hasText: 'DEMONSTRATION — synthetic Beta' })).toBeVisible()
  const syntheticAlpha = availableModels.locator('li').filter({ hasText: /synthetic Alpha/ }).locator('details')
  const exactRoute = syntheticAlpha.locator('p').filter({ hasText: 'Exact route:' })
  await expect(exactRoute).toBeHidden()
  await syntheticAlpha.locator('summary').click()
  await expect(exactRoute).toBeVisible()

  await page.getByRole('link', { name: 'Datasets' }).click()
  await page.getByRole('button', { name: 'Install original CC0 dataset' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'installed' })).toBeVisible()

  await page.getByRole('link', { name: 'Experiments' }).click()
  await expect(page.getByLabel('Try sample questions (default)')).toBeChecked()
  await page.getByRole('button', { name: 'Continue to models' }).click()
  await page.getByLabel('Model A', { exact: true }).selectOption({ index: 1 })
  await page.getByLabel('Model B', { exact: true }).selectOption({ index: 2 })
  await page.getByRole('button', { name: 'Continue to review' }).click()
  await page.getByLabel('Comparison name').fill('Browser demo comparison')
  await expect(page.getByRole('heading', { name: 'Backend request estimate (advisory)' })).toBeVisible()
  const createResponse = page.waitForResponse(response => response.url().endsWith('/api/experiments') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Start comparison' }).click()
  const created = await (await createResponse).json()
  const experimentId = String(created.id)
  expect(experimentId).toBeTruthy()

  const experiment = page.locator('li').filter({ hasText: 'Browser demo comparison' })
  await expect(experiment).toContainText('completed', { timeout: 30_000 })
  await expect(experiment.getByRole('heading', { name: 'Results', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Start comparison', exact: true })).toHaveCount(0)
  await expect(experiment.getByText(/Questions with all answers: 10 of 10/)).toBeVisible()
  await expect(experiment.getByRole('heading', { name: 'Answers side by side' })).toBeVisible()
  await expect(experiment.getByText(/Question:/).first()).toBeVisible()
  await expect(experiment.getByRole('heading', { name: 'Model A (Demonstration fixtures)', exact: true }).first()).toBeVisible()
  await expect(experiment.getByRole('heading', { name: 'Model B (Demonstration fixtures)', exact: true }).first()).toBeVisible()
  await experiment.getByLabel('Hide model names').check()
  await expect(experiment.getByText(/identities are hidden in this results view/)).toBeVisible()
  await expect(experiment.getByRole('heading', { name: 'Model A', exact: true }).first()).toBeVisible()
  for (const format of ['json', 'csv', 'html', 'markdown']) {
    const exported = await page.request.get(`/api/experiments/${experimentId}/export?format=${format}`)
    expect(exported.ok()).toBeTruthy()
    const body = await exported.text()
    expect(body).toContain('DEMONSTRATION')
    expect(body).not.toContain('Bearer ')
  }

  await page.getByRole('link', { name: 'Human Review', exact: true }).click()
  await page.getByLabel('Experiment ID').first().fill(experimentId!)
  await page.getByLabel('Evaluator label').fill('browser-evaluator')
  const assignmentResponse = page.waitForResponse(response => response.url().includes('/api/review/assignments') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Create assignment' }).click()
  const assignment = await (await assignmentResponse).json()
  expect(JSON.stringify(assignment)).not.toContain('fixture/alpha-v1')
  expect(JSON.stringify(assignment)).not.toContain('fixture/beta-v1')
  await expect(page.getByText('Answer A', { exact: true })).toBeVisible()
  await expect(page.getByText('Answer B', { exact: true })).toBeVisible()
  await page.getByRole('radio', { name: 'A wins' }).check()
  await page.getByRole('button', { name: 'Submit review' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Response saved' })).toBeVisible()
  await page.reload()
  await expect(page.getByText('Answer A', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Submitted' })).toBeDisabled()
  await page.getByLabel('Experiment ID').nth(1).fill(experimentId!)
  await page.getByRole('button', { name: 'Load summary' }).click()
  await expect(page.getByText(/Pairwise preference \(not accuracy\)/)).toBeVisible()
  await expect(page.getByText(/1 wins/)).toBeVisible()

  const catalog = await (await page.request.get('/api/models')).json()
  const datasets = await (await page.request.get('/api/datasets')).json()
  const datasetVersionId = datasets[0].versions[0].id
  const longDraft = await page.request.post('/api/experiments', { data: {
    name: 'Browser pause and resume', dataset_version_id: datasetVersionId,
    model_snapshot_ids: catalog.map((row: { id: number }) => row.id), item_ids: null,
    repetitions: 20, retries_per_job: 0, attempt_cap: 400,
  } })
  expect(longDraft.ok()).toBeTruthy()
  await page.getByRole('link', { name: 'Experiments' }).click()
  const longRun = page.locator('li').filter({ hasText: 'Browser pause and resume' })
  const previousRun = page.locator('li').filter({ hasText: 'Browser demo comparison' })
  await expect(longRun.getByRole('button', { name: /Expand/ })).toHaveAttribute('aria-expanded', 'false')
  await expect(previousRun.getByRole('button', { name: /Expand/ })).toHaveAttribute('aria-expanded', 'false')
  await longRun.getByRole('button', { name: /Expand/ }).click()
  await expect(longRun.getByRole('button', { name: /Collapse/ })).toHaveAttribute('aria-expanded', 'true')
  await expect(previousRun.getByRole('button', { name: /Expand/ })).toHaveAttribute('aria-expanded', 'false')
  page.on('dialog', dialog => dialog.accept())
  await longRun.getByRole('button', { name: 'Start' }).click()
  await longRun.getByRole('button', { name: 'Pause', exact: true }).click()
  await expect(longRun).toContainText('paused')
  await longRun.getByRole('button', { name: 'Resume', exact: true }).click()
  await expect(longRun.getByRole('button', { name: 'Cancel', exact: true })).toBeVisible()
  await longRun.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(longRun).toContainText('cancelled')
})
