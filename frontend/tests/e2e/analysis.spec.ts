import { expect, test } from '@playwright/test'

test('fixture analysis snapshot can be created, reloaded, selected and exported', async ({ page }) => {
  await page.goto('/models')
  await page.getByRole('button', { name: 'Refresh catalog' }).click()
  await page.getByRole('link', { name: 'Datasets' }).click()
  await page.getByRole('button', { name: 'Install original CC0 dataset' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'installed' })).toBeVisible()

  await page.getByRole('link', { name: 'Experiments' }).click()
  await page.getByRole('button', { name: 'Continue to models' }).click()
  await page.getByLabel('Model A', { exact: true }).selectOption({ index: 1 })
  await page.getByLabel('Model B', { exact: true }).selectOption({ index: 2 })
  await page.getByRole('button', { name: 'Continue to review' }).click()
  await page.getByLabel('Comparison name').fill('Analysis snapshot browser check')
  await expect(page.getByRole('heading', { name: 'Backend request estimate (advisory)' })).toBeVisible()
  const createResponse = page.waitForResponse(response => response.url().endsWith('/api/experiments') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Start comparison' }).click()
  const experimentId = String((await (await createResponse).json()).id)
  expect(experimentId).toBeTruthy()
  const experiment = page.locator('li').filter({ hasText: 'Analysis snapshot browser check' })
  await expect(experiment).toContainText('completed', { timeout: 30_000 })

  await experiment.getByRole('button', { name: 'Collapse' }).click()
  await experiment.getByRole('button', { name: 'Expand' }).click()
  await experiment.getByText('Show automatic-check definitions and saved analysis', { exact: true }).click()
  await experiment.getByRole('button', { name: 'Save analysis snapshot' }).click()
  await expect(experiment.getByText(/Snapshot #\d+ · SHA-256/)).toBeVisible()
  await expect(experiment.getByText(/do not produce an overall winner/i)).toBeVisible()
  await page.reload()
  const reloaded = page.locator('li').filter({ hasText: 'Analysis snapshot browser check' })
  await reloaded.getByRole('button', { name: 'Expand' }).click()
  await reloaded.getByText('Show automatic-check definitions and saved analysis', { exact: true }).click()
  await expect(reloaded.getByText(/Snapshot #\d+ · SHA-256/)).toBeVisible()
  const exportLink = reloaded.getByRole('link', { name: 'Download report + snapshot (JSON)', exact: true })
  await expect(exportLink).toHaveAttribute('href', /analysis_id=/)
  const response = await page.request.get(await exportLink.getAttribute('href')!)
  expect(response.ok()).toBeTruthy()
})
